export type IconName = keyof typeof ICONS

export function Icon({
  name,
  size = 14,
  className,
}: {
  name: IconName
  size?: number
  className?: string
}) {
  const Glyph = ICONS[name]
  return (
    <Glyph
      className={cx(styles.icon, className)}
      size={size}
      // Lucide draws on a 24 grid; a fixed pixel stroke keeps small icons from going faint.
      strokeWidth={size <= 12 ? 1.5 : 1.75}
      absoluteStrokeWidth
      aria-hidden="true"
    />
  )
}
