import { FEATURES } from '@netherforge/format/constants'
import type { ApiSpec, EventSpec, FeatureId, LuaClass } from '../../src/types.ts'

/** The feature table `since` is read against: format's, unless a test hands its own ([useFeatures]). */
let features: Record<FeatureId, { since: string }> = FEATURES

/**
 * The test hook: reads `since` against [table] until the returned function puts format's back
 * (format's table may hold nothing a test could rely on).
 */
export function useFeatures(table: Record<FeatureId, { since: string }>): () => void {
  features = table
  return () => {
    features = FEATURES
  }
}

/** The Minecraft version a feature the spec names in `since` arrived in, from format's feature table. */
export function sinceVersion(feature: FeatureId): string {
  const found = features[feature]
  if (!found) throw new Error(`"${feature}" isn't in format's feature table (game/Features.kt)`)
  return found.since
}

