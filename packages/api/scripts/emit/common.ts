/** Every class that has events (`:on`), `nf` first: the classes with an `<Class>.Event` alias. */
export function eventedClasses(spec: ApiSpec): (LuaClass & { events: EventSpec[] })[] {
  return spec.classes.filter(
    (it): it is LuaClass & { events: EventSpec[] } => (it.events?.length ?? 0) > 0,
  )
}

/** The alias of a class's event names, which `on`'s `event` parameter is typed as: `Centity.Event`. */
export const eventAlias = (cls: { name: string }) => `${cls.name}.Event`
