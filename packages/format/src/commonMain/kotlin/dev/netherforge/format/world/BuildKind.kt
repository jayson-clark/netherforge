package dev.netherforge.format.world

import dev.netherforge.format.ProblemCodes
import dev.netherforge.format.project.Contents
import dev.netherforge.format.project.FilesKind
import dev.netherforge.format.project.KindContext
import dev.netherforge.format.project.Layout
import dev.netherforge.format.project.ResourceContext

/**
 * `builds/<id>/`: a structure too big for one structure file, as a grid of parts (`<x>_<y>_<z>.nbt`, each a
 * structure file of at most [Builds.PART_SIDE] a side); its first part, `0_0_0.nbt`, makes a folder one. Captured
 * from the dev server or imported from a schematic by the editor or the CLI, placed by scripts over several ticks
 * (`world:place_gradually`), never generated by the world. Scripts name builds and structures alike, so a build
 * can't take a structure's id.
 */
object BuildKind : FilesKind<BuildFile>("build", "builds", Layout.Folder(Builds.MAIN), Contents.BINARY) {
    override fun of(id: String, files: List<String>) = BuildFile(id, Builds.gridOf(files))

    override fun validate(value: BuildFile, ctx: ResourceContext) {
        for (file in ctx.files.sorted()) {
            if (Builds.partOf(file) == null) {
                ctx.problem(
                    ProblemCodes.BUILD_PART_NAME,
                    ctx.pathIn(this, file),
                    "$file isn't a part of the build: parts are <x>_<y>_<z>.nbt, their place in the grid (0_0_0.nbt, 1_0_0.nbt…)"
                )
            }
        }
        val grid = value.grid
        val over = listOf("x" to grid.x, "y" to grid.y, "z" to grid.z).filter { (_, parts) -> parts > Builds.MAX_PARTS }
        if (over.isNotEmpty()) {
            ctx.sink.report(
                ProblemCodes.BUILD_SIZE,
                "The build has ${over.joinToString(" and ") { (axis, parts) -> "$parts parts along $axis" }}; " +
                    "a build has at most ${Builds.MAX_PARTS} along each (${Builds.MAX_PARTS * Builds.PART_SIDE} blocks)"
            )
            return
        }
        val missing = grid.parts.map { it.file }.filter { it !in ctx.files }
        if (missing.isNotEmpty()) {
            val shown =
                missing.take(MISSING_SHOWN).joinToString(", ") +
                    if (missing.size > MISSING_SHOWN) " and ${missing.size - MISSING_SHOWN} more" else ""
            ctx.sink.report(
                ProblemCodes.BUILD_PART_MISSING,
                "The build's parts make a ${grid.x} × ${grid.y} × ${grid.z} grid, but $shown ${if (missing.size == 1) "isn't" else "aren't"} there"
            )
        }
    }

    override fun crossCheck(value: BuildFile, ctx: KindContext) {
        if (ctx.id !in ctx.models(StructureKind)) return
        ctx.sink.report(
            ProblemCodes.BUILD_ID_TAKEN,
            "${ctx.placeOf(
                StructureKind,
                ctx.id
            ).path} has the id \"${ctx.id}\" too, and scripts name structures and builds alike: rename one"
        )
    }

    /** How many missing parts a problem names before it counts the rest. */
    private const val MISSING_SHOWN = 5
}
