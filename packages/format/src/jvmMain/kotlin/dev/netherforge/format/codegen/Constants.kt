    /**
     * `KINDS`, format's registry of resource kinds ([Kinds.all], in reload
     * order) as the editor reads it, and the kind id types derived from it.
     * The editor looks kinds up here rather than listing them.
     */
    private fun StringBuilder.kinds() {
        append("/** What the editor knows of a resource kind (format's `KindSpec`). */\n")
        append("export interface KindInfo {\n")
        append("  /** The project folder its resources live in. */\n")
        append("  folder: string\n")
        append("  /** A folder per resource (`<folder>/<id>/…`), or one file (`<folder>/<id><extension>`). */\n")
        append("  layout: 'folder' | 'file'\n")
        append(
            "  /** The file that makes a folder a resource; null for a single-file kind, or a folder any file makes one (a module). */\n"
        )
        append("  main: string | null\n")
        append("  /** A single-file kind's extension. */\n")
        append("  extension: string | null\n")
        append("  /** A single-file kind's companion document, beside the file and named like it (a structure's `.json`). */\n")
        append("  companion: string | null\n")
        append(
            "  /** JSON format reads (a document kind of the same id), Lua or SQL (files only the server runs), or Minecraft's binary files only the server reads. */\n"
        )
        append("  contents: 'json' | 'lua' | 'sql' | 'binary'\n")
        append("  /** Its resources run Lua: `newScript` and `newSiblingFile` take it. */\n")
        append("  scripted: boolean\n")
        append("  /** `newResourceFiles` makes one (given game data, for a kind whose new files need it). */\n")
        append("  template: boolean\n")
        append("  /** Its resources may sit in group folders (`items/(weapons)/ruby_wand/`): all but a resource pack's. */\n")
        append("  groupable: boolean\n")
        append("  /** A package may list its resources in `exports`: all but what belongs to the package alone (its migrations). */\n")
        append("  exportable: boolean\n")
        append("}\n\n")
        append("/** Every resource kind, in the order a reload batch reloads them. */\n")
        append("export const KINDS = {\n")
        for (kind in Kinds.all) {
            val layout = kind.layout
            val extension = (layout as? Layout.SingleFile)?.extension
            val companion = (layout as? Layout.SingleFile)?.companion
            append(
                "  ${key(kind.id)}: { folder: ${str(kind.folder)}, layout: ${str(if (layout is Layout.Folder) "folder" else "file")}, " +
                    "main: ${opt(
                        kind.mainFile
                    )}, extension: ${opt(extension)}, companion: ${opt(companion)}, contents: ${str(kind.contents.name.lowercase())}, " +
                    "scripted: ${kind.script != null}, template: ${kind.template("id", TEMPLATE_GAME) != null}, " +
                    "groupable: ${kind.groupable}, exportable: ${kind.exportable} },\n"
            )
        }
        append("} as const satisfies Record<string, KindInfo>\n")
        append("export type KindId = keyof typeof KINDS\n")
        append("/** The kinds whose resources are JSON documents: each has an editor. */\n")
        append("export type DocumentResourceKindId = { [K in KindId]: (typeof KINDS)[K]['contents'] extends 'json' ? K : never }[KindId]\n")
        append("/** The kinds whose files are Minecraft's own: never read as text. */\n")
        append("export type BinaryKindId = { [K in KindId]: (typeof KINDS)[K]['contents'] extends 'binary' ? K : never }[KindId]\n")
        append("/** The kinds whose resources run Lua. */\n")
        append("export type ScriptedKindId = { [K in KindId]: (typeof KINDS)[K]['scripted'] extends true ? K : never }[KindId]\n")
        append("/** The kinds `newResourceFiles` makes. */\n")
        append("export type TemplateKindId = { [K in KindId]: (typeof KINDS)[K]['template'] extends true ? K : never }[KindId]\n\n")
    }

    /** `PROBLEM_CODES`, format's catalogue of problems ([ProblemCodes]): what a `Problem.code` can be. */
    private fun StringBuilder.problemCodes() {
        append(
            "/** Every problem code (format's `ProblemCodes`): its severity, and its entry in the docs (`docs/format/problems.md`). */\n"
        )
        append("export const PROBLEM_CODES = {\n")
        for (code in ProblemCodes.all) {
            val severity = str(CanonicalJson.serialName(code.severity))
            append("  ${str(code.code)}: { severity: $severity, docs: ${str("format/problems#${code.anchor}")} },\n")
        }
        append("} as const satisfies Record<string, { severity: Severity; docs: string }>\n")
        append("export type ProblemCode = keyof typeof PROBLEM_CODES\n")
    }

    private fun opt(text: String?) = text?.let(::str) ?: "null"

    /** `ResourcePackFile`'s keyed entry kinds (`skins`, …) and each one's fields marked `@Ref(RefKind.TEXTURE)`. */
    private fun resourcePackTextureFields(): List<Pair<String, List<String>>> {
        val pack = ResourcePackFile.serializer().descriptor
        return (0 until pack.elementsCount).mapNotNull { i ->
            val element = pack.getElementDescriptor(i)
            if (element.kind != StructureKind.MAP) return@mapNotNull null
            val entry = element.getElementDescriptor(1)
            val fields = (0 until entry.elementsCount).filter { j ->
                entry.getElementAnnotations(j).any { it is Ref && it.kind == RefKind.TEXTURE }
            }.map(entry::getElementName)
            if (fields.isEmpty()) null else pack.getElementName(i) to fields
        }
    }

    private fun str(text: String) = JsonPrimitive(text).toString()

    private fun num(value: Double) = CanonicalJson.formatNumber(value.toString())

    private fun key(name: String) = if (Regex("^[A-Za-z_][A-Za-z0-9_]*$").matches(name)) name else str(name)

    /** A JS regex literal for a Kotlin pattern (both use the same syntax for everything format writes). */
    private fun regex(pattern: String) = "/" + pattern.replace("/", "\\/") + "/"
