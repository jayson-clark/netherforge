const GENERATED_BY =
  'Generated by packages/platform/scripts/generate.ts from packages/platform/src/spec. Edit the spec, then run `pnpm generate`.'

const KEYWORDS = new Set(
  (
    'as async await break const continue dyn else enum extern false fn for if impl in let loop ' +
    'match mod move mut pub ref return static struct trait true type unsafe use where while ' +
    'abstract become box do final macro override priv typeof unsized virtual yield try gen'
  ).split(' '),
)

/** `displayName` → `display_name`; `type` → `r#type`. */
export function snake(name: string): string {
  const out = name
    .replace(/([a-z0-9])([A-Z])/g, '$1_$2')
    .replace(/([A-Z])([A-Z][a-z])/g, '$1_$2')
    .toLowerCase()
  if (out === 'self') return 'self_'
  return KEYWORDS.has(out) ? `r#${out}` : out
}

/** `ON_GROUND` → `OnGround`. */
const variant = (name: string) =>
  name
    .toLowerCase()
    .split('_')
    .map((part) => part[0]!.toUpperCase() + part.slice(1))
    .join('')

function rustdoc(doc: string | undefined, indent: string): string[] {
  if (!doc?.trim()) return []
  return doc
    .trim()
    .split('\n')
    .map((line) => `${indent}///${line.trim() ? ` ${line.trimEnd()}` : ''}`)
}

const PRIMITIVE_RUST: Record<string, string> = {
  String: 'String',
  Int: 'i32',
  Long: 'i64',
  Short: 'i16',
  Byte: 'i8',
  Double: 'f64',
  Float: 'f32',
  Boolean: 'bool',
  Unit: '()',
  UUID: 'Uuid',
  ByteArray: 'Vec<u8>',
  IntArray: 'Vec<i32>',
  ShortArray: 'Vec<i16>',
  BooleanArray: 'Vec<bool>',
  Any: 'Dynamic',
  Throwable: 'PlatformError',
}

interface Context {
  interfaces: Set<string>
  unions: Set<string>
}

/** [position]: an interface returned is borrowed from the implementation; taken, it's shared. */
function rustType(node: TypeNode, cx: Context, position: 'in' | 'out' | 'field'): string {
  switch (node.kind) {
    case 'star':
      return 'Dynamic'
    case 'optional':
      return `Option<${rustType(node.inner, cx, position)}>`
    case 'function': {
      const params = node.params.map((p) => rustType(p.type, cx, 'in')).join(', ')
      const returns = rustType(node.returns, cx, 'out')
      return `Box<dyn Fn(${params})${returns === '()' ? '' : ` -> ${returns}`}>`
    }
    case 'named': {
      const args = node.args.map((a) => rustType(a, cx, position === 'out' ? 'field' : position))
      switch (node.name) {
        case 'List':
        case 'Set':
          return `Vec<${args[0]}>`
        case 'Map':
          return `HashMap<${args[0]}, ${args[1]}>`
        case 'Pair':
        case 'Triple':
          return `(${args.join(', ')})`
        case 'Result':
          return `Result<${args[0]}, PlatformError>`
      }
      const primitive = PRIMITIVE_RUST[node.name]
      if (primitive) return primitive
      const ported = RUST_EXTERNAL[node.name]
      if (ported?.interface)
        return position === 'out' ? `&dyn ${ported.path}` : `Rc<dyn ${ported.path}>`
      if (ported) return ported.path
      if (node.name in EXTERNAL) return `external::${node.name.split('.').pop()}`
      const [outer, inner] = node.name.split('.')
      if (inner && cx.unions.has(outer!)) return `${outer}${inner}`
      if (cx.interfaces.has(node.name)) {
        if (position === 'out') return `&dyn ${node.name}`
        return `Rc<dyn ${node.name}>`
      }
      return node.name
    }
  }
}

const typeOf = (text: string, cx: Context, position: 'in' | 'out' | 'field') =>
  rustType(parseType(text), cx, position)

function fieldDoc(field: Param): string | undefined {
  const parts = [
    field.doc,
    field.default !== undefined ? `Default: \`${field.default}\`.` : undefined,
  ]
  return parts.filter(Boolean).join('\n\n') || undefined
}

/** Whether a struct of [fields] can derive `Clone`, `Debug` and `PartialEq`: no closures in it. */
const plain = (fields: Param[]) => !fields.some((f) => f.type.includes('->'))

function struct(name: string, doc: string | undefined, fields: Param[], cx: Context): string[] {
  return [
    ...rustdoc(doc, ''),
    ...(plain(fields) ? ['#[derive(Clone, Debug, PartialEq)]'] : []),
    `pub struct ${name} {`,
    ...fields.flatMap((f) => [
      ...rustdoc(fieldDoc(f), '    '),
      `    pub ${snake(f.name)}: ${typeOf(f.type, cx, 'field')},`,
    ]),
    '}',
    '',
  ]
}

/** An enum entry's argument as a Rust value of its parameter's type. */
function literal(arg: string, type: string): string {
  if (type === 'String') return arg.startsWith('"') ? `${arg}` : JSON.stringify(arg)
  if (type === 'Double' || type === 'Float') return /[.eE]/.test(arg) ? arg : `${arg}.0`
  return arg
}

/**
 * Records whose Kotlin class keeps its state private and works on it in methods: a utility both sides have, not
 * data that crosses as fields. Each is written by hand in the platform crate, at this path.
 */
const HAND_WRITTEN: Record<string, string> = {
  ChunkGrid: 'crate::chunk_grid::ChunkGrid',
}

function decl(d: Decl, cx: Context): string[] {
  switch (d.kind) {
    case 'record':
      if (HAND_WRITTEN[d.name]) {
        return [...rustdoc(d.doc, ''), `pub use ${HAND_WRITTEN[d.name]};`, '']
      }
      return struct(d.name, d.doc, d.fields, cx)
    case 'enum': {
      const lines = [
        ...rustdoc(d.doc, ''),
        '#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash, PartialOrd, Ord)]',
        `pub enum ${d.name} {`,
        ...d.entries.flatMap((e) => [...rustdoc(e.doc, '    '), `    ${variant(e.name)},`]),
        '}',
        '',
        `impl ${d.name} {`,
        `    /// Every entry, in the spec's order.`,
        `    pub const ALL: &'static [${d.name}] = &[${d.entries.map((e) => `${d.name}::${variant(e.name)}`).join(', ')}];`,
        '',
        '    /// Its name as the spec spells it (`ON_GROUND`).',
        "    pub fn name(self) -> &'static str {",
        '        match self {',
        ...d.entries.map(
          (e) => `            ${d.name}::${variant(e.name)} => ${JSON.stringify(e.name)},`,
        ),
        '        }',
        '    }',
      ]
      d.params.forEach((p, k) => {
        const type = p.type === 'String' ? "&'static str" : typeOf(p.type, cx, 'field')
        lines.push(
          '',
          ...rustdoc(p.doc, '    '),
          `    pub fn ${snake(p.name)}(self) -> ${type} {`,
          '        match self {',
          ...d.entries.map(
            (e) =>
              `            ${d.name}::${variant(e.name)} => ${literal(e.args[k] ?? p.default ?? '', p.type)},`,
          ),
          '        }',
          '    }',
        )
      })
      lines.push('}', '')
      return lines
    }
    case 'union': {
      const lines: string[] = []
      for (const c of d.cases) lines.push(...struct(`${d.name}${c.name}`, c.doc, c.fields, cx))
      lines.push(
        ...rustdoc(d.doc, ''),
        ...(d.cases.every((c) => plain(c.fields)) ? ['#[derive(Clone, Debug, PartialEq)]'] : []),
        `pub enum ${d.name} {`,
        ...d.cases.map((c) => `    ${c.name}(${d.name}${c.name}),`),
        '}',
        '',
      )
      return lines
    }
    case 'interface':
    case 'object':
      return trait(d, cx)
  }
}

/** A trait's members, once: each one's doc, its signature, and what it returns. */
interface Member {
  doc: string | undefined
  name: string
  /** Its parameters' names, as the signature has them. */
  params: string[]
  /** `fn name(&self, a: A) -> R`, without the `;`. */
  signature: string
  /** What an implementation without a body takes its parameters as: `fn name(&self, _: A) -> R`. */
  unnamed: string
  returns: string
}

function members(d: InterfaceDecl, cx: Context): Member[] {
  const out: Member[] = []
  const member = (
    doc: string | undefined,
    name: string,
    params: [string, string][],
    returns: string,
  ) => {
    const tail = returns === '()' ? '' : ` -> ${returns}`
    out.push({
      doc,
      name,
      params: params.map(([n]) => n),
      signature: `fn ${name}(&self${params.map(([n, t]) => `, ${n}: ${t}`).join('')})${tail}`,
      unnamed: `fn ${name}(&self${params.map(([, t]) => `, _: ${t}`).join('')})${tail}`,
      returns,
    })
  }
  // An object's values are what its methods read.
  for (const f of [...(d.fields ?? []), ...d.properties])
    member(f.doc, snake(f.name), [], typeOf(f.type, cx, 'out'))
  // Kotlin overloads a name (`contents(ref)`, `contents(ref, filter)`); Rust can't, so a later
  // one is named by its last parameter: `contents_with_filter`.
  const seen = new Set<string>()
  for (const m of d.methods) {
    let name = snake(m.name)
    if (seen.has(name))
      name = `${name}_with_${snake(m.params[m.params.length - 1]!.name).replace(/^r#/, '')}`
    seen.add(name)
    const params = m.params.map((p): [string, string] => [snake(p.name), typeOf(p.type, cx, 'in')])
    member(m.doc, name, params, typeOf(m.returns, cx, 'out'))
  }
  return out
}

function trait(d: InterfaceDecl, cx: Context): string[] {
  const lines = [...rustdoc(d.doc, ''), `pub trait ${d.name}${d.extends ? `: ${d.extends}` : ''} {`]
  for (const m of members(d, cx)) lines.push(...rustdoc(m.doc, '    '), `    ${m.signature};`, '')
  if (lines[lines.length - 1] === '') lines.pop()
  lines.push('}', '')
  return lines
}

/**
 * `Unported`: every interface of the spec implemented by one stand-in, whose
 * groups are itself and whose every other answer is a panic naming it
 * (`TeamOps::create isn't on this platform`). A fake implements the groups it
 * means and hands back `&Unported` for the rest, so it's written as the
 * runtime's ported parts need it, and the compiler holds it to the spec.
 */
function unported(all: Decl[], cx: Context): string[] {
  const lines = [
    `// ${GENERATED_BY}`,
    '',
    "//! `Unported`: the Platform's every group, each answer a panic naming it.",
    '',
    'use super::*;',
    '',
    '/// Every group of the Platform, none of them there: a fake starts from it.',
    '#[derive(Clone, Copy, Debug, Default)]',
    'pub struct Unported;',
    '',
    '/// What asking `Unported` anything but a group does.',
    '#[track_caller]',
    'pub fn unported(what: &str) -> ! {',
    '    panic!("{what} isn\'t on this platform")',
    '}',
    '',
  ]
  for (const d of all) {
    if (d.kind !== 'interface' && d.kind !== 'object') continue
    lines.push(`impl ${d.name} for Unported {`)
    for (const m of members(d, cx)) {
      const group = /^&dyn \w+$/.test(m.returns)
      const name = m.signature.slice(3, m.signature.indexOf('('))
      lines.push(
        `    ${m.unnamed} {`,
        group ? '        &Unported' : `        unported("${d.name}::${name}")`,
        '    }',
        '',
      )
    }
    if (lines[lines.length - 1] === '') lines.pop()
    lines.push('}', '')
    // What a fake implements of `X` when it means only some of it: the rest is `Unported`'s.
    const fake = `Fake${d.name}`
    lines.push(
      `/// A [\`${d.name}\`] that means only some of it: implement this, and every method it`,
      "/// doesn't answers as [`Unported`] does.",
      `pub trait ${fake}${d.extends ? `: ${d.extends}` : ''} {`,
    )
    for (const m of members(d, cx))
      lines.push(
        `    ${m.signature} {`,
        `        <Unported as ${d.name}>::${m.name}(&Unported${m.params.map((p) => `, ${p}`).join('')})`,
        '    }',
        '',
      )
    if (lines[lines.length - 1] === '') lines.pop()
    lines.push('}', '', `impl<T: ${fake}> ${d.name} for T {`)
    for (const m of members(d, cx))
      lines.push(
        `    ${m.signature} {`,
        `        ${fake}::${m.name}(self${m.params.map((p) => `, ${p}`).join('')})`,
        '    }',
        '',
      )
    if (lines[lines.length - 1] === '') lines.pop()
    lines.push('}', '')
  }
  return lines
}

/** The generated modules, by file name: one per spec file, and `mod.rs` naming them. */
export function platformRust(
  spec: PlatformFile[],
  specName: (source: string) => string,
): Map<string, string> {
  const all = spec.flatMap((f) => f.decls)
  const cx: Context = {
    interfaces: new Set(
      all.filter((d) => d.kind === 'interface' || d.kind === 'object').map((d) => d.name),
    ),
    unions: new Set(all.filter((d) => d.kind === 'union').map((d) => d.name)),
  }
  const out = new Map<string, string>()
  const modules: string[] = []
  for (const file of spec) {
    const module = snake(specName(file.source)).replace(/^r#/, '')
    modules.push(module)
    const lines = [
      `// ${GENERATED_BY}`,
      '',
      `//! What \`${file.source}\` in the Kotlin runtime's \`platform/\` holds.`,
      '',
      'use super::*;',
      '',
      ...file.decls.flatMap((d) => decl(d, cx)),
    ]
    out.set(
      `${module}.rs`,
      `${lines
        .join('\n')
        .replace(/\n{3,}/g, '\n\n')
        .trimEnd()}\n`,
    )
  }
  out.set('unported.rs', `${unported(all, cx).join('\n').trimEnd()}\n`)
  out.set(
    'external.rs',
    [
      `// ${GENERATED_BY}`,
      '',
      "//! The types the boundary carries that the spec doesn't declare (`EXTERNAL`): format's,",
      "//! the Lua API's and the runtime's. Each is a placeholder until its side is ported to Rust,",
      '//! carrying the value as a `Dynamic` (its JSON); then the generator names its real type',
      "//! instead (`RUST_EXTERNAL` in packages/platform/scripts/rust.ts) and it's gone from here.",
      '',
      'use super::Dynamic;',
      '',
      ...Object.entries(EXTERNAL)
        .filter(([name]) => !(name in RUST_EXTERNAL))
        .flatMap(([name, owner]) => [
          `/// ${owner.startsWith('runtime') || owner === 'api' ? `The ${owner === 'api' ? 'Lua API' : 'runtime'}'s` : `format's \`${owner}\``} \`${name.split('.').pop()}\`.`,
          '#[derive(Clone, Debug, PartialEq)]',
          `pub struct ${name.split('.').pop()}(pub Dynamic);`,
          '',
        ]),
    ].join('\n'),
  )
  out.set(
    'mod.rs',
    [
      `// ${GENERATED_BY}`,
      '',
      '//! The Platform, a module per spec file, everything re-exported here.',
      '',
      '#![allow(clippy::all, unused_imports)]',
      '',
      'pub use std::collections::HashMap;',
      'pub use std::rc::Rc;',
      '',
      'pub use crate::{Dynamic, PlatformError, Uuid};',
      '',
      'pub mod external;',
      'pub mod unported;',
      '',
      ...modules.map((m) => `mod ${m};`),
      '',
      ...modules.map((m) => `pub use ${m}::*;`),
      'pub use unported::*;',
      '',
    ].join('\n'),
  )
  return out
}
